def blend(a, b, t):
    return {k: a.get(k, 0.0) + (b.get(k, 0.0) - a.get(k, 0.0)) * t for k in set(a) | set(b)}


def walk_pose(phase, base=None):
    """one moment of the walk cycle (phase in radians)"""
    p = dict(base or POSES["stand"])
    s = math.sin(phase)
    p["thigh_n"] = 26 * s
    p["thigh_f"] = -26 * s
    p["shin_n"] = p["thigh_n"] - (34 * max(0.0, -math.cos(phase)) if s < 0.3 else 0) - 4
    p["shin_f"] = p["thigh_f"] - (34 * max(0.0, math.cos(phase)) if -s < 0.3 else 0) - 4
    p["uarm_n"] = -20 * s
    p["farm_n"] = -20 * s + 14
    p["uarm_f"] = 20 * s
    p["farm_f"] = 20 * s + 14
    p["torso"] = 5
    return p


def run_pose(phase, base=None):
    """one moment of the run cycle: longer strides, bent elbows pumping, the body leaning forward"""
    p = dict(base or POSES["stand"])
    s = math.sin(phase)
    p["thigh_n"] = 42 * s + 6
    p["thigh_f"] = -42 * s + 6
    p["shin_n"] = p["thigh_n"] - (70 * max(0.0, -math.cos(phase)) if s < 0.4 else 8) - 6
    p["shin_f"] = p["thigh_f"] - (70 * max(0.0, math.cos(phase)) if -s < 0.4 else 8) - 6
    p["uarm_n"] = -40 * s
    p["farm_n"] = -40 * s + 85
    p["uarm_f"] = 40 * s
    p["farm_f"] = 40 * s + 85
    p["torso"] = 16
    p["hip"] = 140
    return p


def variant(design, seed):
    """a different person of the same kind (another shirt / hair) - two young men never look identical"""
    d = dict(design)
    if d.get("faceless"):
        return d
    rng = np.random.default_rng(seed)
    shirts = [(150, 96, 52), (60, 120, 160), (70, 130, 70), (120, 60, 120), (40, 90, 170), (170, 170, 175), (50, 60, 140)]
    col = shirts[int(rng.integers(0, len(shirts)))]
    d["shirt"], d["shirt_dark"] = col, tuple(int(c * 0.75) for c in col)
    if d.get("sari"):
        d["lower"] = col
    if d.get("hair_style") == "short" and rng.uniform() < 0.5:
        d["moustache"] = None
    return d


def _smooth(pts, it=2):
    """Chaikin corner cutting: a closed polygon -> a soft rounded outline (no box-like body)"""
    for _ in range(it):
        out = []
        n = len(pts)
        for i in range(n):
            (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % n]
            out += [(0.75 * x0 + 0.25 * x1, 0.75 * y0 + 0.25 * y1), (0.25 * x0 + 0.75 * x1, 0.25 * y0 + 0.75 * y1)]
        pts = out
    return pts


class Character:
    """one rigged character. state per frame: x, ground_y, facing (-1..1 continuous: body turn), head_yaw (-1..1),
    head_pitch, gaze (gx, gy in -1..1), blink 0..1, mouth (open 0..1, shape), brows, pose dict, scale"""

    def __init__(self, cid, design, scale=1.0):
        self.id, self.d, self.scale = cid, design, scale
        self.h = design.get("height", 1.0)
        self.b = design.get("build", 1.0)

    # -------------------------------------------------------------- the skeleton
    def joints(self, st):
        """hips + legs follow 'facing'; chest, shoulders, arms follow 'facing_upper' (a twist at the waist - the
        legs never spin with the body); turning towards the camera makes the shoulders wider, not thinner"""
        k = self.scale * self.h
        f = st["facing"]
        fu = st.get("facing_upper", f)
        fw = 1 if f >= 0 else -1
        squash = max(0.3, abs(f))
        sq_u = max(0.3, abs(fu))
        p = st["pose"]
        x0, gy = st["x"], st["ground_y"]
        hip = (x0, gy - p["hip"] * k)

        def seg(a, ang, ln, sq):
            r = math.radians(ang)
            return (a[0] + math.sin(r) * ln * k * fw * (sq if abs(ang) < 120 else 1), a[1] + math.cos(r) * ln * k)

        lean = math.radians(p["torso"])
        bend = math.radians(p.get("chest", 0.0))           # the upper back bends a little more than the hips
        chest = (hip[0] + math.sin(lean) * 70 * k * fw * sq_u, hip[1] - math.cos(lean) * 70 * k)
        neck = (chest[0] + math.sin(lean + bend) * 48 * k * fw * sq_u, chest[1] - math.cos(lean + bend) * 48 * k)
        spread = (6 + 26 * (1 - sq_u)) * k                 # front view: the shoulders are far apart
        shrug = p.get("shrug", 0.0) * k
        sh_n = (neck[0] + spread * fw, neck[1] + 12 * k - shrug)
        sh_f = (neck[0] - spread * fw, neck[1] + 12 * k - shrug)
        hs = (4 + 10 * (1 - squash)) * k
        kn_n = seg((hip[0] + hs * fw, hip[1]), p["thigh_n"], 75, squash)
        ft_n = seg(kn_n, p["shin_n"], 72, squash)
        kn_f = seg((hip[0] - hs * fw, hip[1]), p["thigh_f"], 75, squash)
        ft_f = seg(kn_f, p["shin_f"], 72, squash)
        el_n = seg(sh_n, p["uarm_n"], 55, sq_u)
        hd_n = seg(el_n, p["farm_n"], 50, sq_u)
        el_f = seg(sh_f, p["uarm_f"], 55, sq_u)
        hd_f = seg(el_f, p["farm_f"], 50, sq_u)
        pitch = math.radians(st.get("head_pitch", 0.0))
        tl = lean + bend
        head = (neck[0] + math.sin(tl * 0.6 + pitch * 0.3) * 46 * k * fw, neck[1] - math.cos(tl * 0.4) * 46 * k
                + st.get("head_pitch", 0.0) * 0.35 * k)
        return {"hip": hip, "chest": chest, "neck": neck, "sh_n": sh_n, "sh_f": sh_f, "kn_n": kn_n, "ft_n": ft_n, "kn_f": kn_f,
                "ft_f": ft_f, "el_n": el_n, "hd_n": hd_n, "el_f": el_f, "hd_f": hd_f, "head": head, "k": k, "fw": fw,
                "squash": squash, "sq_u": sq_u}

    def foot_floor(self, st):
        """the lowest foot must touch the ground: the y shift that makes it so (no floating, no sinking)"""
        j = self.joints(st)
        low = max(j["ft_n"][1], j["ft_f"][1])
        return st["ground_y"] - low - 4 * j["k"]

    # -------------------------------------------------------------- drawing
    INK = (24, 20, 26)

    def draw(self, pt, st):
        d = self.d
        st = dict(st)
        if st.get("planted", True):
            st["ground_y"] = st["ground_y"] + self.foot_floor(st)
        st["ground_y"] -= st.get("float", 0.0)           # a ghost hovers (its feet never touch)
        j = self.joints(st)
        k, fw = j["k"], j["fw"]
        self.last_joints = j
        old_ink = pt.ink
        pt.ink = (d.get("ink", self.INK), 2.3 * k) if d.get("ink", True) is not None else None
        lower, shirt, skin = d["lower"], d["shirt"], d["skin"]
        hand_col = skin if not d.get("faceless") else shirt
        far = lambda col: _shade(col, 0.74)
        t = st.get("t", 0.0)
        mode_n = st.get("fingers") or ("open" if st.get("hand_open", 0.0) > 0.2 else "relaxed")
        mode_f = st.get("fingers_f") or ("open" if mode_n in ("open", "spread") else "relaxed")
        legs_hidden = d.get("sari") or d.get("robe")
        dhoti = d.get("dhoti") and not legs_hidden
        only = st.get("only")                              # (draw only some parts: the test pictures of single pieces)
        want = lambda x: only is None or x in only
        if (not legs_hidden or d.get("ghost")) and want("legs"):
            self._leg(pt, j["hip"], j["kn_f"], j["ft_f"], k, fw, far(lower), far(d["feet"]), far(skin))
        if want("far_arm"):
            self._arm(pt, j["sh_f"], j["el_f"], j["hd_f"], k, far(shirt), far(hand_col), mode_f, t, fw, 0.7)
        if d.get("carry") == "staff":                       # a bamboo staff in the far hand
            h = j["hd_f"]
            pt.limb((h[0] + fw * 4 * k, h[1] - 90 * k), (h[0] - fw * 6 * k, h[1] + 150 * k), 7 * k, 6 * k, (40, 90, 130))
        if not legs_hidden and want("legs"):
            self._leg(pt, j["hip"], j["kn_n"], j["ft_n"], k, fw, lower, d["feet"], skin)
        if dhoti and want("legs"):                                          # the dhoti: ONE draped cloth from the waist to mid-shin
            pts = []
            hip = j["hip"]
            for kn, ft in ((j["kn_n"], j["ft_n"]), (j["kn_f"], j["ft_f"])):
                mid = (kn[0] + (ft[0] - kn[0]) * 0.62, kn[1] + (ft[1] - kn[1]) * 0.62)
                for c_ in (kn, mid):
                    for ang in range(0, 360, 45):
                        pts.append((c_[0] + math.cos(math.radians(ang)) * 17 * k * self.b, c_[1] + math.sin(math.radians(ang)) * 17 * k * self.b))
            for ang in range(0, 360, 30):
                pts.append((hip[0] + math.cos(math.radians(ang)) * 32 * k * self.b, hip[1] + math.sin(math.radians(ang)) * 22 * k))
            hull = cv2.convexHull(np.array(pts, np.float32)).reshape(-1, 2)
            pt.poly(_smooth([tuple(p_) for p_ in hull], 1), lower)
            kn = j["kn_n"]
            pt.line((hip[0] + fw * 10 * k, hip[1] + 10 * k), (kn[0], kn[1] + 4 * k), _shade(lower, 0.8), 2.4 * k)   # a fold
        if want("head") or want("hair_back"):
            self._back_hair(pt, j["head"], k * 1.16, st)
        if want("torso") or (want("legs") and legs_hidden):
            self._torso(pt, j, k, fw, d, st)
        hx, hy = j["head"]
        if want("head"):
            pt.limb(j["neck"], (hx, hy + 30 * k), 17 * k, 15 * k, skin, shade=-fw)       # the neck
            self._head(pt, j["head"], k * 1.16, st)
        if want("near_arm"):
            self._arm(pt, j["sh_n"], j["el_n"], j["hd_n"], k, shirt, hand_col, mode_n, t, fw, 1.0)
        if d.get("carry") == "torch" and st.get("lantern") is None:   # a small torch in the near hand
            h = j["hd_n"]
            a0 = math.atan2(h[1] - j["el_n"][1], h[0] - j["el_n"][0])
            pt.limb((h[0] - math.cos(a0) * 4 * k, h[1] - math.sin(a0) * 4 * k), (h[0] + math.cos(a0) * 22 * k, h[1] + math.sin(a0) * 22 * k),
                    9 * k, 11 * k, (40, 40, 46))
        pt.ink = old_ink
        return j

    @staticmethod
    def _side(a, b, fw):
        """which side of a limb is away from the light (the cel-shaded side)"""
        dx, dy = b[0] - a[0], b[1] - a[1]
        ln = math.hypot(dx, dy) or 1
        nx, ny = -dy / ln, dx / ln
        if abs(nx) > 0.35:
            return -fw if nx > 0 else fw
        return 1 if ny > 0 else -1

    def _torso(self, pt, j, k, fw, d, st):
        """a rounded body: hips, waist, chest, round shoulders - the outline follows the bending spine"""
        hip, chest, neck = j["hip"], j["chest"], j["neck"]
        b = self.b
        sq_u, sq = j["sq_u"], j["squash"]
        front = 1 + 0.35 * (1 - sq_u)
        ww, sw = 28 * k * b * (1 + 0.15 * (1 - sq)), 35 * k * b * front
